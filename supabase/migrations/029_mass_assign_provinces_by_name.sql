CREATE TEMP VIEW _profile_labels AS
SELECT
  p.id,
  p.email,
  p.role,
  p.full_name,
  p.name_prefix,
  regexp_replace(
    trim(both FROM concat_ws(' ', NULLIF(trim(p.name_prefix), ''), NULLIF(trim(p.full_name), ''))),
    '\s+',
    ' ',
    'g'
  ) AS display_name,
  regexp_replace(trim(p.full_name), '\s+', ' ', 'g') AS bare_name
FROM public.user_profiles p
WHERE p.role IN ('volunteer', 'overseer')
  AND COALESCE(p.disabled, false) = false;

-- Resolve existing match (prefer prefix+name, then bare full_name)
CREATE TEMP TABLE _matched AS
SELECT DISTINCT ON (r.seq)
  r.seq,
  r.display_name,
  r.name_prefix,
  r.bare_name,
  r.provinces,
  pl.id AS profile_id
FROM _province_roster r
LEFT JOIN _profile_labels pl
  ON pl.display_name = r.display_name
  OR pl.bare_name = r.bare_name
  OR pl.bare_name = r.display_name
ORDER BY r.seq, CASE WHEN pl.display_name = r.display_name THEN 0 ELSE 1 END;

-- ---------------------------------------------------------------------------
-- A) Update provinces for existing matches
-- ---------------------------------------------------------------------------
UPDATE public.user_profiles AS up
SET
  assigned_provinces = (
    SELECT ARRAY(
      SELECT DISTINCT trim(x)
      FROM unnest(m.provinces) AS x
      WHERE trim(x) <> ''
      ORDER BY 1
    )
  ),
  name_prefix = COALESCE(NULLIF(trim(up.name_prefix), ''), m.name_prefix),
  updated_at = timezone('utc', now())
FROM _matched m
WHERE m.profile_id IS NOT NULL
  AND up.id = m.profile_id;

-- ---------------------------------------------------------------------------
-- B) Create missing volunteers
-- ---------------------------------------------------------------------------
CREATE TEMP TABLE _to_create AS
SELECT
  m.seq,
  m.display_name,
  m.name_prefix,
  m.bare_name,
  m.provinces,
  gen_random_uuid() AS id,
  NULL::text AS login_id,
  NULL::text AS auth_email
FROM _matched m
WHERE m.profile_id IS NULL;

-- Assign VL### login ids (sequential among new rows; start after max existing VL#)
WITH ranked AS (
  SELECT
    c.ctid AS rid,
    row_number() OVER (ORDER BY c.seq) AS rn
  FROM _to_create c
),
next_start AS (
  SELECT COALESCE(
    (
      SELECT max(n)
      FROM (
        SELECT CASE
          WHEN upper(split_part(coalesce(email, ''), '@', 1)) ~ '^VL[0-9]+$' THEN
            substring(upper(split_part(email, '@', 1)) from 3)::int
          WHEN upper(email) ~ '^VL[0-9]+$' THEN
            substring(upper(email) from 3)::int
          ELSE 0
        END AS n
        FROM public.user_profiles
      ) s
    ),
    0
  ) + 1 AS start_n
)
UPDATE _to_create c
SET
  login_id = 'VL' || lpad((ns.start_n + r.rn - 1)::text, 3, '0'),
  auth_email =
    lower('VL' || lpad((ns.start_n + r.rn - 1)::text, 3, '0')) || '@edu.local'
FROM ranked r
CROSS JOIN next_start ns
WHERE c.ctid = r.rid;

INSERT INTO auth.users (
  instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, email_change, email_change_token_new, recovery_token
)
SELECT
  COALESCE(
    (SELECT id FROM auth.instances LIMIT 1),
    '00000000-0000-0000-0000-000000000000'::uuid
  ),
  c.id,
  'authenticated',
  'authenticated',
  c.auth_email,
  crypt('password12345', gen_salt('bf')),
  timezone('utc', now()),
  '{"provider":"email","providers":["email"]}'::jsonb,
  jsonb_build_object(
    'full_name', c.bare_name,
    'name_prefix', c.name_prefix,
    'role', 'volunteer',
    'login_id', c.login_id
  ),
  timezone('utc', now()),
  timezone('utc', now()),
  '', '', '', ''
FROM _to_create c
ON CONFLICT (id) DO NOTHING;

INSERT INTO auth.identities (
  id, user_id, identity_data, provider, provider_id,
  last_sign_in_at, created_at, updated_at
)
SELECT
  c.id, c.id,
  jsonb_build_object('sub', c.id::text, 'email', c.auth_email, 'email_verified', true),
  'email', c.auth_email,
  timezone('utc', now()), timezone('utc', now()), timezone('utc', now())
FROM _to_create c
ON CONFLICT DO NOTHING;

INSERT INTO public.user_profiles (
  id, email, full_name, name_prefix, position, role, overseer_tier,
  assigned_zone, assigned_provinces, assigned_districts,
  reports_to, birthday, disabled, must_change_password
)
SELECT
  c.id,
  c.login_id,
  c.bare_name,
  c.name_prefix,
  'อาสาสมัคร',
  'volunteer',
  NULL,
  NULL,
  (
    SELECT ARRAY(
      SELECT DISTINCT trim(x)
      FROM unnest(c.provinces) AS x
      WHERE trim(x) <> ''
      ORDER BY 1
    )
  ),
  '{}'::text[],
  NULL,
  NULL,
  false,
  false
FROM _to_create c
ON CONFLICT (id) DO UPDATE SET
  email = EXCLUDED.email,
  full_name = EXCLUDED.full_name,
  name_prefix = EXCLUDED.name_prefix,
  position = EXCLUDED.position,
  role = EXCLUDED.role,
  assigned_provinces = EXCLUDED.assigned_provinces,
  disabled = false,
  updated_at = timezone('utc', now());

